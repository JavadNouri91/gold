/** Returns cities for a given province name (empty array if not found). */
export function getCitiesForProvince(provinceName: string): string[] {
  const province = IRAN_PROVINCES.find((p) => p.name === provinceName);
  return province?.cities ?? [];
}

/** Returns all province names sorted by Persian alphabet. */
export function getProvinceNames(): string[] {
  return IRAN_PROVINCES.map((p) => p.name).sort((a, b) =>
    a.localeCompare(b, 'fa'),
  );
}
